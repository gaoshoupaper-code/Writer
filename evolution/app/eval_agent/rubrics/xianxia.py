# 组名 → 对应的交付物 agent short name（供 applicable_groups 判断）
_GROUP_AGENT_MAP = {
    "general": None,  # 通用五维基于全部交付物 + trace 整体，不绑定单一 agent
    "storybuilding": "storybuilding",
    "outline": "detail-outline",
    "body": "writing",
}


def applicable_groups(deliveries: dict[str, dict[str, str]]) -> dict[str, list[dict]]:
    """根据交付物判断启用哪些评分组。

    通用五维始终启用。其他组按对应 agent 是否有交付物启用。
    """
    groups: dict[str, list[dict]] = {"general": GENERAL_DIMENSIONS}
    for group_name, agent in _GROUP_AGENT_MAP.items():
        if agent and agent in deliveries and deliveries[agent]:
            groups[group_name] = ALL_GROUPS[group_name]
    return groups


def build_group_rubric_prompt(group_name: str, dimensions: list[dict]) -> str:
    """构造某评分组的 rubric prompt 片段。"""
    label = GROUP_LABELS.get(group_name, group_name)
    lines = [
        f"你是玄幻/修仙网文的质量评估员。请从**{label}**角度评估下面这部作品的相关产物。",
        f"按以下 {len(dimensions)} 个维度逐一打分，每个维度在 1-5 整数区间打分，",
        "1/3/5 三档为核心锚点参考（1=严重不满足，3=基本满足，5=稳定优秀），",
        "2/4 表示相邻锚点之间的明确程度。\n",
    ]
    for dim in dimensions:
        lines.append(f"### {dim['key']}")
        lines.append(f"评估问题：{dim['question']}")
        lines.append(f"- 1 分（严重不满足）：{dim['anchors']['1']}")
        lines.append(f"- 3 分（基本满足）：{dim['anchors']['3']}")
        lines.append(f"- 5 分（稳定优秀）：{dim['anchors']['5']}")
        lines.append("")

    # 正文组额外注入 AI 味锚点清单
    if group_name == "body":
        lines.append("### AI 味检测锚点清单（用于「全局AI味一致性」维度）")
        lines.append("逐条对照以下痕迹判断 AI 味是系统性泛滥还是偶发：")
        for i, p in enumerate(AI_ANTI_PATTERNS, 1):
            lines.append(f"{i}. {p}")
        lines.append("")

    lines.append("注意：")
    lines.append("- 用户任务契约中明确的风格/节奏/反套路偏好优先于默认商业标准。")
    lines.append("- 需要跨段比较的维度（高开低走、全局AI味），文本范围不足时 score 设为 0 并在 evidence 写'无法判断'。")
    lines.append("- 评分必须基于可观察的证据，不猜测。")
    return "\n".join(lines)


def build_output_format(dim_keys: list[str]) -> str:
    """构造 judge 必须返回的 JSON 格式说明（五级锚定制）。"""
    keys_json = ", ".join(f'"{k}": 0' for k in dim_keys)
    return f"""
请严格按以下 JSON 格式返回（不要任何额外文字、不要 markdown 代码块）：
{{
  "scores": {{{keys_json}}},
  "evidence": "{{每个维度一句话说明打分依据}}",
  "verdict": "pass|review|fail"
}}
所有分值在 1-5 整数区间。2/4 表示介于相邻锚点之间。
score=0 且 evidence 含'无法判断'表示证据不足。
evidence 必须包含每个维度的依据。"""


def group_dim_keys(group_name: str) -> list[str]:
    """返回某组的维度 key 列表。"""
    return [d["key"] for d in ALL_GROUPS.get(group_name, [])]


